insert into storage.buckets (id, name, public)
values ('project-images', 'project-images', true)
on conflict (id) do nothing;

drop policy if exists project_images_upload on storage.objects;
create policy project_images_upload on storage.objects for insert to authenticated
with check (bucket_id = 'project-images' and public.my_role() in ('admin', 'field'));

