-- 026_wa_triage — فرز Jev لعروض واتساب قبل إرسالها للمساعد (docs/JEV.md).
--
-- ما يضيفه:
--   * wa_triage: حكم الفرز (send | review | skip) لكل نص كتلة ومجموعة أسئلة، مع أسبابه وإجابات Jev واحتمالاتها،
--     وتصحيح المالك للنية. المفتاح بصمة النص؛ لا يُحفظ نص الرسالة ولا المرسل ولا جوال. المدير يقرأ، والكتابة من
--     مفتاح الخدمة وحده (وظيفة wa-triage).
--   * wa_triage_calls: سطر لكل نداء للوظيفة، من الصفحة أو من أداة التقييم: العناصر ونداءات Jev والرموز والتكلفة.
--   * wa_triage_tickets: تذاكر أداة التقييم (بصمة السر، سقف عناصر، تاريخ انتهاء). لا يصلها إلا مفتاح الخدمة.
--   * wa_triage_take_ticket: يحجز عناصر النداء من تذكرة في UPDATE واحد.
--   * wa_triage_budget: إنفاق الفرز اليوم بتوقيت الرياض مع سقفه. لا تناديه إلا الوظيفة.
--   * wa_triage_report: ملخص للمدير لكل مجموعة أسئلة: الأحكام وما أُرسل منها للمساعد، وشرائح ثقة النية،
--     وتصحيحات المالك، وتصنيف المحلّل × الحكم، والتكلفة.
--   * إعدادان في crm_settings: wa_triage_daily_usd_cap = 0.5 دولار، و wa_triage_mode = "suggest".
--
-- Jev يقترح فقط: لا يكتب في agent_requests ولا agent_drafts ولا projects ولا clients، ولا يصل شيء إلى المساعد إلا
-- حين يضغط المالك «إرسال للمساعد». agent_router_budget() لا يتغير: سقف المساعد (agent_daily_usd_cap) لا يشمل
-- الفرز، وللفرز سقفه المستقل.

-- ============================================================
-- (1) أحكام الفرز
-- ============================================================
-- صف لكل (نص، مجموعة أسئلة). المفتاح sha256 (hex) لنص الكتلة الأصلي بعد trim، يحسبه الخادم: النص نفسه في تصدير
-- جديد أو في مجموعة أخرى يجد حكمه بلا نداء، وتغيير الأسئلة (qset جديد) يعني حكماً جديداً.
-- source_shas: بصمات «نص المصدر» لنسخ الكتلة كما تحسبها الصفحة (المجموعة والمرسل ووقت النشر ثم النص)، وهي نفسها
-- agent_sources.sha256 حين تُرسل النسخة للمساعد؛ بها يعرف التقرير ما أُرسل.
-- answers: intent و city باحتمالاتهما كاملة، و kind و district بأعلى ثلاثة [[المفتاح، الاحتمال]، …]، و multiple {noul}.
-- owner_label: النية الصحيحة في رأي المالك (أحد مفاتيح intent الستة)، مع وقتها وصاحبها.
create table if not exists public.wa_triage (
    key            text not null,                 -- sha256 hex لنص الكتلة بعد trim
    qset           text not null,                 -- مجموعة الأسئلة: wa-1 …
    model          text not null,                 -- كما ردّه OpenRouter، أو ما تكتبه الوظيفة لحكم الكود بلا نداء
    verdict        text not null check (verdict in ('send', 'review', 'skip')),
    reasons        text[] not null default '{}',
    answers        jsonb not null,
    regex_kind     text,                          -- تصنيف المحلّل في الصفحة: offer | update | wanted | other | document
    source_shas    text[] not null default '{}',
    input_tokens   int,
    cost_usd       numeric(10,6),
    owner_label    text check (owner_label in ('sale_offer', 'rent_offer', 'status_update', 'wanted', 'not_property', 'other')),
    owner_label_at timestamptz,
    owner_label_by uuid references public.profiles(id),
    created_by     uuid references public.profiles(id),
    created_at     timestamptz not null default now(),
    updated_at     timestamptz not null default now(),
    primary key (key, qset)
);
create index if not exists wa_triage_created_idx     on public.wa_triage (created_at);
create index if not exists wa_triage_source_shas_idx on public.wa_triage using gin (source_shas);

alter table public.wa_triage enable row level security;
revoke all on public.wa_triage from anon, authenticated;
grant select on public.wa_triage to authenticated;
drop policy if exists wa_triage_admin_read on public.wa_triage;
create policy wa_triage_admin_read on public.wa_triage
    for select to authenticated using (public.is_admin());
-- لا سياسة إدخال أو تعديل أو حذف: مفتاح الخدمة (وظيفة wa-triage) يتجاوز RLS، وتصحيح المالك يمرّ بإجراء label فيها.

