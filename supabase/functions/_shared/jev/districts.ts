/* ===================== التطبيع ===================== */

// تطبيع حرفي مشترك للرسالة وللأسماء. لا يحذف «حي» من أول النص (normDistrictText يحذفها من قيمة الحي وحدها).
// علامات التنسيق (اتجاه النص، الوصل والفصل غير المرئيين) والتشكيل والتطويل تُحذف؛ المسافات تُختصر.
function fold(s: string): string {
  return asciiDigits(String(s ?? ""))
    .replace(/[\p{Cf}\p{Mn}ـ]/gu, "")
    .replace(/[أإآٱ]/g, "ا")
    .replace(/ة/g, "ه")
    .replace(/[ىی]/g, "ي")
    .replace(/ک/g, "ك")
    .toLowerCase()
    .replace(/\s+/g, " ")
    .trim();
}

// ما ليس من الاسم في أول قيمة الحي وآخرها: الترقيم والرموز، و«حي »/«مخطط » (مرة أو أكثر)
const LEADING = /^(?:[^\p{L}\p{N}]+|(?:حي|مخطط)(?!\p{L}))+/u;
const TRAILING = /[^\p{L}\p{N}]+$/u;

// الأرقام لاتينية، بلا تشكيل ولا تطويل، أإآٱ→ا، ة→ه، ى→ي، مسافة واحدة، ثم يسقط من الأول «حي »/«مخطط »
// والترقيم: «- حي المروة» → «المروه». للرسالة كاملة استعمل findDistrictCandidates.
export function normDistrictText(s: string): string {
  return fold(s).replace(LEADING, "").replace(TRAILING, "");
}

/* ===================== المطابقة ===================== */

// الشكل المطبَّع لكل اسم وبديل → الاسم المعتمد
const FORMS = new Map<string, string>();
for (const district of JEDDAH_DISTRICTS) {
  for (const raw of [district.name, ...district.aliases]) {
    const form = normDistrictText(raw);
    if (form && !FORMS.has(form)) FORMS.set(form, district.name);
  }
}

const escapeRe = (s: string) => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");

// الأطول أولاً: في الموضع نفسه يغلب «أبحر الشمالية» «أبحر»، ويُتخطّى ما داخل المطابقة
const DISTRICT_RE = new RegExp(
  "(?<!\\p{L})(?:" +
    [...FORMS.keys()].sort((a, b) => b.length - a.length || (a < b ? -1 : 1)).map(escapeRe).join("|") +
    ")(?!\\p{L})",
  "gu",
);

// الأحياء المذكورة في الرسالة بأسمائها المعتمدة، بترتيب أول ذكر (المواصفة §4)، وكل حي مرة واحدة، وأقصى عدد
// MAX_DISTRICT_CANDIDATES (أول ما ذُكر). الرسالة الخالية من الأحياء → []. أيها حيّ العقار يختاره Jev لا الكود.
export function findDistrictCandidates(message: string): string[] {
  const text = fold(message);
  if (!text) return [];
  const found = new Set<string>();
  for (const m of text.matchAll(DISTRICT_RE)) {
    const name = FORMS.get(m[0]);
    if (!name) continue;
    found.add(name);
    if (found.size >= MAX_DISTRICT_CANDIDATES) break;
  }
  return [...found];
}

// الاسم المعتمد لقيمة حي كاملة («حي المروه»، «ابحر الجنوبية»، «مخطط سندس»)، أو null إن لم تكن في القائمة
export function canonicalDistrict(value: string): string | null {
  return FORMS.get(normDistrictText(value)) ?? null;
}
